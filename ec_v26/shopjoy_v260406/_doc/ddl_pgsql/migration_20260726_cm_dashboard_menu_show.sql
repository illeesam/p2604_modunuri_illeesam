-- ============================================================================
-- cm_dashboard — 좌측메뉴 노출 설정 (2026-07-26)
--
-- 배경: 개인 대시보드를 여러 개 만들면 좌측메뉴 '사용자대시보드' 그룹에 전부 나와
--       목록이 길어진다. 자주 쓰지 않는 것은 메뉴에서 감출 수 있어야 한다.
--
-- menu_show_yn : 'Y' 면 좌측메뉴에 노출. 'N' 이면 메뉴에서 감춘다(대시보드 자체는 유지되고
--                '내 대시보드 관리' 화면의 칩으로는 계속 접근할 수 있다).
--
-- 순서는 이미 있는 sort_ord 를 그대로 쓴다 — 별도 컬럼을 만들지 않는다.
--
-- ※ 깊이(depth)는 넣지 않았다. 개인 대시보드는 보통 3~5개이고 좌측메뉴에서 이미
--   '사용자대시보드' 그룹 아래 한 단계로 들어가 있어, 계층을 더 두면 접기/펼치기
--   상태 관리 비용에 비해 얻는 것이 적다. 항목이 많아지면 그때 그룹명 한 단계만 추가한다.
-- ============================================================================

ALTER TABLE shopjoy_2604.cm_dashboard ADD COLUMN IF NOT EXISTS menu_show_yn CHAR(1) DEFAULT 'Y';

UPDATE shopjoy_2604.cm_dashboard SET menu_show_yn = 'Y' WHERE menu_show_yn IS NULL;

COMMENT ON COLUMN shopjoy_2604.cm_dashboard.menu_show_yn IS
  '좌측메뉴 노출 여부 (Y/N). N 이면 메뉴에서 감춤 — 대시보드는 유지되고 관리화면 칩으로 접근 가능. 순서는 sort_ord';
