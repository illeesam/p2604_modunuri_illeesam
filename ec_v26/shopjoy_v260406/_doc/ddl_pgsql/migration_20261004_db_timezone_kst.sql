-- ═══════════════════════════════════════════════════════════
--  DB 기본 시간대 한국시간(+9) — Asia/Seoul
--  작성일: 2026-10-04
--
--  배경(사용자 "한국시간 +9 맞춰달라고 한 거 개선"):
--   NAS 의 백엔드(ecBeBo)·CDN·FO 컨테이너가 UTC 로 돌아 등록일시(reg_date 등)·ID 의 yyMMddHHmmss 가 9시간 이르게 저장됐다.
--   2026-10-04 13:52 KST 부터 컨테이너에 TZ=Asia/Seoul 을 주고(docker-compose), 백엔드 main() 에서도 JVM 기본 시간대를 고정했다.
--   백엔드는 JDBC 접속 때 자기 시간대(이제 KST)로 세션을 맞추므로 앱이 쓰는 값은 이것으로 해결된다.
--   이 스크립트는 DB 자체의 기본 시간대(지금 UTC)를 바꿔, 시간대를 따로 지정하지 않는 접속(DBeaver·psql·파이썬 도구·DB 함수
--   now()/CURRENT_TIMESTAMP 를 쓰는 수동 쿼리)도 한국시간으로 보이게 한다. 이미 저장된 값은 바꾸지 않는다.
--
--  ⚠ 기존 데이터: 9월~2026-10-04 13:52 사이 NAS 백엔드가 만든 행의 *_date 는 UTC 기준(9시간 이름)으로 남아 있다.
--     어떤 행이 NAS(UTC)·로컬(KST) 중 어디서 만들어졌는지 구분할 수 없어 일괄 +9시간 보정은 하지 않는다(정렬이 조금 섞일 수 있음).
-- ═══════════════════════════════════════════════════════════
--  사용법: postgres(DB 소유자)로 실행. 새로 맺는 접속부터 적용된다(이미 열린 접속은 다시 연결).
-- ═══════════════════════════════════════════════════════════

ALTER DATABASE postgres SET timezone TO 'Asia/Seoul';

